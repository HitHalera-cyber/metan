function img(file, caption, widthPx = 620) {
  const buf = fs.readFileSync(path.join(IMG, file));
  const s = imageSize(buf);
  const w = Math.min(widthPx, s.w);
  const h = Math.round(s.h * w / s.w);
  figN += 1;
  return [
    new Paragraph({ alignment: AlignmentType.CENTER, spacing: { before: 120, after: 60 },
      keepNext: true,
      children: [new ImageRun({ type: s.type, data: buf,
        transformation: { width: w, height: h },
        altText: { title: caption, description: caption, name: file } })] }),
    new Paragraph({ alignment: AlignmentType.CENTER, spacing: { after: 200 },
      children: [new TextRun({ text: `Рисунок ${figN} – ${caption}`, italics: true,
        size: 20, color: MUTED })] }),
  ];
}

const border = { style: BorderStyle.SINGLE, size: 4, color: "D3DBD9" };
const borders = { top: border, bottom: border, left: border, right: border };

function table(caption, header, rows, widths) {
  tabN += 1;
  const total = widths.reduce((a, b) => a + b, 0);
  const cell = (text, w, head) => new TableCell({
    borders, width: { size: w, type: WidthType.DXA },
    shading: head ? { fill: "E6F2EF", type: ShadingType.CLEAR, color: "auto" } : undefined,
    margins: { top: 60, bottom: 60, left: 100, right: 100 },
    children: String(text).split("\n").map((line) => new Paragraph({ spacing: { after: 0 },
      children: [new TextRun({ text: line, bold: head, size: 19 })] })),
  });
  return [
    new Paragraph({ spacing: { before: 160, after: 80 }, keepNext: true,
      children: [new TextRun({ text: `Таблица ${tabN} – ${caption}`, italics: true,
        size: 20, color: MUTED })] }),
    new Table({
      width: { size: total, type: WidthType.DXA }, columnWidths: widths,
      rows: [new TableRow({ tableHeader: true,
        children: header.map((h, k) => cell(h, widths[k], true)) }),
      ...rows.map((r) => new TableRow({ children: r.map((v, k) => cell(v, widths[k], false)) }))],
    }),
    new Paragraph({ spacing: { after: 120 }, children: [] }),
  ];
}

function note(title, text) {
  const nb = { style: BorderStyle.SINGLE, size: 6, color: TEAL };
  return [new Table({
    width: { size: TEXT_W, type: WidthType.DXA }, columnWidths: [TEXT_W],
    rows: [new TableRow({ children: [new TableCell({
      borders: { top: nb, bottom: nb, left: nb, right: nb },
      width: { size: TEXT_W, type: WidthType.DXA },
      shading: { fill: "EEF7F5", type: ShadingType.CLEAR, color: "auto" },
      margins: { top: 100, bottom: 100, left: 160, right: 160 },
      children: [new Paragraph({ spacing: { after: 60 },
        children: [new TextRun({ text: title, bold: true, color: TEAL })] }),
      ...(Array.isArray(text) ? text : [text]).map((t) => new Paragraph({
        spacing: { after: 40 }, children: [new TextRun({ text: t, size: 21 })] }))],
    })] })],
  }), new Paragraph({ spacing: { after: 120 }, children: [] })];
}

