"""Исходные данные расчёта.

Значения взяты из BLOCK DATA (RK1.FOR) и главной программы (RK2.FOR)
варианта met21_ispr. Внутренние имена полей - как в Фортране (P, ALFA,
DKR, ...): они используются в JSON-файлах, командной строке и протоколе
shi10.dat. В окне программы величины показываются в обозначениях,
принятых в учебниках по ракетным двигателям (pк, α, dкр, ...): поле
``sym`` в описании параметра.

Отличия от исходной программы (подробно - в руководстве):
* ALFA - значение α первого варианта (в Фортране к ALFA сначала
  прибавлялся шаг: 0.6 + 0.2 = 0.8). По умолчанию считается один вариант.
* Узлы горла и начала сужения (JC, IC, IC1) вычисляются по размерам
  камеры (GRID_AUTO = 2); число узлов и узлы-границы задаёт пользователь.
* Params.fortran() - точный набор данных исходной программы.
"""

