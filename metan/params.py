def _radial_segments(p):
    """Радиальные участки (длина, мм) между границами струй и стенок."""
    r = [0., p.DCMB / 2., p.DOGOR / 2., p.DOGOR / 2. + p.DELGOR, p.DKAR / 2.,
         p.DOOK / 2., p.DOOK / 2. + p.DELOK, p.DKS / 2.]
    return [r[k + 1] - r[k] for k in range(7)], r


def _share(total, lengths, minimum):
    """Разделить total интервалов по участкам пропорционально длинам, не
    меньше minimum (число или список) на участок (метод наибольших
    остатков)."""
    n = list(minimum) if isinstance(minimum, (list, tuple)) else \
        [minimum] * len(lengths)
    rest = total - sum(n)
    if rest < 0:
        raise ValueError("мало узлов")
    s = sum(lengths)
    want = [rest * L / s for L in lengths]
    add = [int(w) for w in want]
    left = rest - sum(add)
    order = sorted(range(len(lengths)), key=lambda k: want[k] - add[k],
                   reverse=True)
    for k in order[:left]:
        add[k] += 1
    return [a + b for a, b in zip(n, add)]


def derived_nodes(p, J=None, IC2=None):
    """Узлы, которые определяются размерами камеры (а не выбором
    подробности сетки), - как их найдёт подпрограмма GRID:

    JC  - первый узел по радиусу с r ≥ dкр/2 (горло);
    IC  = Nx − 1 - горло по длине (за ним 1 интервал выходного участка,
          как в исходной программе);
    IC1 = IC − (Nr − JC) - начало сужения: на конусе по одному узлу на
          каждый узел по радиусу (стенка конуса - «лесенка» по узлам).

    J - номера границ по радиусу [1, JZ, JZ1, JA, JA3, JA1, JA2, JN].
    """
    L, r = _radial_segments(p)
    if J is None:
        J = [1, p.JZ, p.JZ1, p.JA, p.JA3, p.JA1, p.JA2, p.JN]
    if IC2 is None:
        IC2 = p.IC2
    names = ("оси и JZ", "JZ и JZ1", "JZ1 и JA", "JA и JA3", "JA3 и JA1",
             "JA1 и JA2", "JA2 и Nr")
    for k in range(7):
        if J[k + 1] - J[k] < 1:
            raise ValueError("Между %s нет ни одного интервала сетки "
                             "(номера узлов-границ должны расти)" % names[k])
    JN = J[7]
    x2 = [0.] * (JN + 1)
    for seg in range(7):
        j0, j1 = J[seg], J[seg + 1]
        for j in range(j0 + 1, j1 + 1):
            x2[j] = r[seg] + (r[seg + 1] - r[seg]) * (j - j0) / (j1 - j0)
    tol = 1e-9 * p.DKR
    JC = next((j for j in range(2, JN + 1) if p.DKR / 2. - x2[j] <= tol), None)
    if JC is None:
        raise ValueError("Критическое сечение dкр должно быть меньше Dк")
    IC = p.IN - 1
    IC1 = IC - (JN - JC)
    if IC2 < 2:
        raise ValueError("Узел конца предкамеры IC2 должен быть ≥ 2")
    if IC1 - IC2 < 2:
        raise ValueError(
            "Мало узлов вдоль оси: начало сужения IC1 = Nx − 1 − (Nr − JC) = "
            "%d, а нужно хотя бы IC2 + 2 = %d. Увеличьте Nx до %d или "
            "уменьшите IC2" % (IC1, IC2 + 2, p.IN + IC2 + 2 - IC1))
    return dict(JC=JC, IC=IC, IC1=IC1)


def auto_grid(p):
    """Все узлы сетки.

    GRID_AUTO = 2: границы JZ…JA2 и IC2 - как задал пользователь, JC, IC, IC1
    вычисляются (derived_nodes). GRID_AUTO = 1 (и кнопка «Расставить
    пропорционально») - границы тоже расставляются автоматически:

    По радиусу JN−1 интервалов делятся между семью участками (центральная
    струя, промежуток до щели горючего, щель горючего, стенка предкамеры,
    уступ, щель окислителя, зазор до стенки камеры) пропорционально их
    ширине, но не меньше 3 интервалов на струю и 2 на остальные участки.

    По длине: за критическим сечением 1 интервал (как в исходной
    программе), на конус - по одному узлу на узел по радиусу (так устроено
    сужение в GRID), остальные IN − 2 − (JN − JC) интервалов делятся между
    предкамерой и цилиндрической частью пропорционально их длинам (не
    меньше 3 на каждую).
    """
    L, r = _radial_segments(p)
    if min(L) <= 0:
        raise ValueError("Размеры по радиусу не по порядку: нужно "
                         "dц < dг, dг + 2δг < dпк < dок, dок + 2δок < Dк")
    if p.GRID_AUTO == 2:
        d = derived_nodes(p)
        d.update(JZ=p.JZ, JZ1=p.JZ1, JA=p.JA, JA3=p.JA3, JA1=p.JA1,
                 JA2=p.JA2, IC2=p.IC2)
        return d
    return proportional_grid(p)


def proportional_grid(p):
    """Границы пропорционально размерам камеры (см. auto_grid)."""
    L, r = _radial_segments(p)
    if min(L) <= 0:
        raise ValueError("Размеры по радиусу не по порядку: нужно "
                         "dц < dг, dг + 2δг < dпк < dок, dок + 2δок < Dк")
    if p.JN - 1 < 18:
        raise ValueError("Узлов по радиусу Nr должно быть не меньше 19")
    # струи (центральная, щели горючего и окислителя) - не меньше 3
    # интервалов, чтобы профиль скорости в них не терялся
    n = _share(p.JN - 1, L, [3, 2, 3, 2, 2, 3, 2])
    J = [1]
    for k in n:
        J.append(J[-1] + k)
    JZ, JZ1, JA, JA3, JA1, JA2, JN = J[1:]
    d = derived_nodes(p, J, IC2=2)  # IC2 ниже; здесь - только JC, IC, IC1
    JC, IC, IC1 = d["JC"], d["IC"], d["IC1"]
    axial = IC1 - 1
    if axial < 6:
        raise ValueError("Мало узлов вдоль оси: Nx должно быть не меньше %d"
                         % (p.IN + 6 - axial))
    n1, n2 = _share(axial, [p.DELKAR, p.ALKS], 3)
    IC2 = 1 + n1
    return dict(JZ=JZ, JZ1=JZ1, JA=JA, JA3=JA3, JA1=JA1, JA2=JA2, JC=JC,
                IC=IC, IC1=IC1, IC2=IC2)


