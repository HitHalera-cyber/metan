def geometry_warnings(p):
    """Проверка геометрии до расчёта: список понятных предупреждений."""
    w = []
    if not p.DCMB < p.DOGOR:
        w.append("Центральная струя dц должна быть меньше dг.")
    if not p.DOGOR + 2 * p.DELGOR < p.DKAR:
        w.append("Щель горючего (dг + 2δг) не помещается в предкамеру dпк.")
    if not p.DKAR < p.DOOK:
        w.append("Щель окислителя dок должна быть больше диаметра предкамеры dпк.")
    if not p.DOOK + 2 * p.DELOK < p.DKS:
        w.append("Щель окислителя (dок + 2δок) не помещается в камеру Dк.")
    if not p.DKR < p.DKS:
        w.append("Критическое сечение dкр должно быть меньше Dк.")
    if p.DKR > p.DKAR:
        w.append("dкр больше диаметра предкамеры - необычная схема, проверьте.")
    if p.GRID_AUTO != 1:
        for a, b, name in ((1, p.JZ, "оси и JZ"), (p.JZ, p.JZ1, "JZ и JZ1"),
                           (p.JZ1, p.JA, "JZ1 и JA"), (p.JA, p.JA3, "JA и JA3"),
                           (p.JA3, p.JA1, "JA3 и JA1"), (p.JA1, p.JA2, "JA1 и JA2"),
                           (p.JA2, p.JN, "JA2 и JN")):
            if b - a < 1:
                w.append("Между %s нет ни одного интервала сетки." % name)
    return w
