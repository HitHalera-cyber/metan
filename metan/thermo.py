RU = 8.314462618e-3       # кДж/(моль·K)
P0 = 101325.0


def _coef(T):
    """Коэффициенты NASA для всех веществ при температуре T (9 x 7)."""
    hi = T > NASA[:, 0]
    return np.where(hi[:, None], NASA[:, 1:8], NASA[:, 8:15])


def h_RT(T):
    a = _coef(T)
    return (a[:, 0] + a[:, 1] * T / 2 + a[:, 2] * T ** 2 / 3 + a[:, 3] * T ** 3 / 4
            + a[:, 4] * T ** 4 / 5 + a[:, 5] / T)


def s_R(T):
    a = _coef(T)
    return (a[:, 0] * np.log(T) + a[:, 1] * T + a[:, 2] * T ** 2 / 2
            + a[:, 3] * T ** 3 / 3 + a[:, 4] * T ** 4 / 4 + a[:, 6])


def cp_R(T):
    a = _coef(T)
    return a[:, 0] + a[:, 1] * T + a[:, 2] * T ** 2 + a[:, 3] * T ** 3 + a[:, 4] * T ** 4


def h_mass(T, Y):
    """Энтальпия смеси, кДж/кг (с теплотой образования)."""
    return float(np.sum(Y / M * h_RT(T)) * RU * T * 1000.)


def elements_of(f):
    """Моли элементов C, H, O на 1 г смеси: f - массовая доля CH4,
    1 - f - O2 (элементный состав любой смеси CH4/O2 и её продуктов)."""
    return np.array([f / M[0], 4 * f / M[0], 2 * (1 - f) / M[1]])


def equilibrium_TP(T, P, b, pi=None, lnN=None):
    """Равновесный состав при T, P для элементов b (моль/г).
    Возвращает (моль/г каждого вещества, pi, lnN)."""
    A = ATOMS
    g = h_RT(T) - s_R(T) + np.log(P / P0)          # μ°/RT + ln(P/P0)
    present = b > 1e-14
    if pi is None:
        pi = np.zeros(3)
        lnN = np.log(b.sum() * 0.5 + 1e-12)
    for _ in range(200):
        lx = np.clip(A.T @ pi - g, -700, 50)
        x = np.exp(lx)
        N = np.exp(lnN)
        n = N * x
        R = np.concatenate([[x.sum() - 1.0], A @ n - b])
        if np.max(np.abs(R[1:]) / np.maximum(b, 1e-12) * present) < 1e-10 \
                and abs(R[0]) < 1e-11:
            break
        J = np.zeros((4, 4))
        J[0, :3] = A @ x
        J[1:, :3] = (A * n) @ A.T
        J[1:, 3] = A @ n
        # элементов, которых нет (например, C при f = 0), не решаем
        idx = [0] + [1 + i for i in range(3) if present[i]]
        var = [i for i in range(3) if present[i]] + [3]
        dz = np.linalg.solve(J[np.ix_(idx, var)], -R[idx])
        step = np.max(np.abs(dz))
        if step > 2.0:
            dz *= 2.0 / step
        for k, v in enumerate(var):
            if v == 3:
                lnN += dz[k]
            else:
                pi[v] += dz[k]
        for i in range(3):
            if not present[i]:
                pi[i] = -300.0
    return n, pi, lnN


def equilibrium_HP(h, P, b, T0=2500.0):
    """Равновесные T и массовые доли при энтальпии h (кДж/кг), давлении P."""
    T = T0
    pi = lnN = None
    for _ in range(60):
        n, pi, lnN = equilibrium_TP(T, P, b, pi, lnN)
        Y = n * M / (n * M).sum()
        hT = h_mass(T, Y)
        # равновесная теплоёмкость - численно
        dT = max(1.0, 1e-3 * T)
        n2, _, _ = equilibrium_TP(T + dT, P, b, pi.copy(), lnN)
        Y2 = n2 * M / (n2 * M).sum()
        cp = (h_mass(T + dT, Y2) - hT) / dT
        step = (h - hT) / max(cp, 1e-3)
        step = max(-500.0, min(500.0, step))
        T = min(6000.0, max(250.0, T + step))
        if abs(step) < 1e-3:
            break
    return T, Y, cp


def adiabatic_table(P, h_fuel, h_ox=0.0, n=401):
    """Таблица равновесной температуры по доле горючего f при давлении P:
    энтальпия смеси h(f) = f·h_fuel + (1 − f)·h_ox (адиабатическое смешение).
    Возвращает массивы f, T, cp_eq (кДж/(кг·K)), h."""
    fs = np.linspace(0.0, 1.0, n)
    Ts = np.zeros(n)
    cps = np.zeros(n)
    hs = fs * h_fuel + (1 - fs) * h_ox
    T0 = 400.0
    # от стехиометрии в обе стороны - хорошее начальное приближение
    order = np.argsort(np.abs(fs - 0.2))
    done = {}
    for k in order:
        f = fs[k]
        near = min(done, key=lambda q: abs(q - f)) if done else None
        T0 = done[near] if near is not None else 3000.0
        try:
            T, Y, cp = equilibrium_HP(hs[k], P, elements_of(f), T0)
        except np.linalg.LinAlgError:
            T, cp = T0, 2.0
        Ts[k], cps[k] = T, cp
        done[f] = T
    return fs, Ts, cps, hs
